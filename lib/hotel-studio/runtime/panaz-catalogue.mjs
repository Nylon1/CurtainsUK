export function resolvePanazFabric(value) {
  if (value === null) return null;
  const fabric = PANAZ_FABRICS.find((f) => f.id === value?.id);
  if (!fabric)
    throw Error(
      "Hotel fabric selections must come from the connected Panaz plain FR selection.",
    );
  return structuredClone(fabric);
}
export function listedUse(fabric, item) {
  const use = {
    curtains: "Curtains",
    voile: "Curtains",
    runner: "Bed Throws",
    cushions: "Cushions",
    headboard: "Upholstery",
    base: "Upholstery",
    armchair: "Upholstery",
    bench: "Upholstery",
  }[item];
  return (
    fabric.usage
      .split(", ")
      .map((entry) => (entry === "Curtain" ? "Curtains" : entry))
      .includes(use) &&
    (item !== "voile" || fabric.productType === "Sheer") &&
    (item !== "curtains" || fabric.productType !== "Sheer")
  );
}
