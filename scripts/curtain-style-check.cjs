const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '../shopify-theme/curtainsuk-new-design-live-base');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const section = read('sections/curtainsuk-curtain-style.liquid');
const javascript = section.split('{% javascript %}')[1].split('{% endjavascript %}')[0];
new vm.Script(javascript);
const localeSource = read('locales/en.default.json');
const locale = JSON.parse(localeSource.slice(localeSource.indexOf('{')));
const keys = [...section.matchAll(/'curtain_style\.([^']+)' \| t/g)].map(x => x[1]);
for (const key of keys) assert.ok(key in locale.curtain_style, `Missing translation: ${key}`);
assert.ok(!/fetch\(|localStorage|sessionStorage|cart\/|checkout/.test(javascript), 'Education must not write commerce or customer state');
assert.equal((section.match(/<h1 /g) || []).length, 1);
assert.equal((section.match(/data-style-comparison>/g) || []).length, 3);
assert.equal((section.match(/data-style-panel>/g) || []).length, 7);
assert.ok(!/\/products\/|Tyrone|Austin|fullness=|heading=/.test(section));
assert.deepEqual(JSON.parse(read('templates/page.curtain-style.json')).order, ['curtain_style']);
const nav = read('snippets/curtainsuk-header-navigation.liquid');
assert.ok(nav.includes('?view=curtain-style'));
assert.ok(!nav.includes('href="/pages/samples"'));
assert.ok(read('sections/curtainsuk-help-footer.liquid').includes('href="/pages/samples"'));
console.log(JSON.stringify({javascript:'valid',translations:keys.length,comparisons:3,panels:7,commerceStateWrites:0,tyroneProductLinks:0,samplesFooterRetained:true},null,2));
